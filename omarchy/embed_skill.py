#!/usr/bin/python3
"""Generate the CLI's embedded skill from its canonical Markdown source."""
from pathlib import Path

root = Path(__file__).resolve().parent
content = (root / 'skills/recall/SKILL.md').read_text()
(root / 'embedded_skill.py').write_text('# Generated by embed_skill.py; edit skills/recall/SKILL.md instead.\nSKILL_TEXT = ' + repr(content) + '\n')
