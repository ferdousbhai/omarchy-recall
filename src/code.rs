    #[test]
    fn stretches_end_where_the_code_does() {
        // Three functions of ~25 lines (~1,000 characters each): a 1,800-character stretch can't hold two, and must
        // end at the blank line between them rather than in the middle of the second.
        let text = [function("first", 22, 40), function("second", 22, 40), function("third", 22, 40)].join("\n");
        let pieces = lines(&text, 1800);
        assert_eq!(pieces.len(), 3);
        let heads: Vec<&str> = pieces.iter().map(|piece| piece.text.split('\n').next().unwrap()).collect();
        assert_eq!(heads, ["func first() {", "func second() {", "func third() {"]);
        assert!(pieces.iter().all(|piece| piece.text.ends_with('}')));
        // Line numbers are the file's, from 1, and stretches don't overlap when they end at a break.
        assert!(pieces[0].first == 1 && pieces[0].last == 24);
        assert!(pieces[1].first == 26 && pieces[1].last == 49);
        let all: Vec<&str> = text.split('\n').collect();
        for piece in &pieces {
            assert_eq!(all[piece.first - 1..piece.last].join("\n"), piece.text);
            assert!(piece.text.chars().count() <= 1800);
        }
    }

