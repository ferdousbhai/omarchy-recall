    /// A function of `body` lines, each `width` characters wide.
    fn function(name: &str, body: usize, width: usize) -> String {
        let lines: Vec<String> = (1..=body).map(|n| format!("    let v{n} = \"{}\"", "x".repeat(width))).collect();
        format!("func {name}() {{\n{}\n}}\n", lines.join("\n"))
    }

