//! Code for the code index: a source file, a repo's doc or a notebook, cut into stretches of whole lines (a notebook's
//! into whole cells) that the model reads one at a time, each knowing where it is, so that a result opens there.
//! And names in code: a query that's a name finds it exactly, and the place that defines it rather than every place
//! that uses it.

use std::collections::{HashMap, HashSet};
use std::path::Path;
use std::sync::LazyLock;

