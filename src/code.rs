    #[test]
    fn stretches_end_where_code_breaks() {
        let mut text = String::new();
        for function in 0..30 {
            text.push_str(&format!("def function_{function}(x):\n"));
            for line in 0..6 {
                text.push_str(&format!("    value_{line} = x * {line} + {function}\n"));
            }
            text.push_str("    return value_5\n\n");
        }
        let pieces = lines(&text, 600);
        assert!(pieces.len() > 3);
        // Every stretch starts at a definition: the breaks fell between functions.
        assert!(pieces.iter().all(|piece| piece.text.starts_with("def function_")), "{:?}", pieces[1].text);
        assert!(pieces.iter().all(|piece| piece.text.chars().count() <= 600));
        assert_eq!(pieces[0].first, 1);
        assert_eq!(pieces.last().unwrap().last, line_count(text.trim_end()));
    }

