    // MARK: Notebooks

    fn notebook(cells: &[(&str, &str)], outputs: bool) -> Vec<u8> {
        let list: Vec<serde_json::Value> = cells
            .iter()
            .map(|(kind, source)| {
                let lines: Vec<String> = source.split('\n').map(|line| format!("{line}\n")).collect();
                let mut cell = serde_json::json!({"cell_type": kind, "metadata": {}, "source": lines});
                if *kind == "code" && outputs {
                    cell["outputs"] = serde_json::json!([{"output_type": "display_data",
                        "data": {"image/png": "A".repeat(5000), "text/plain": ["<Figure>"]}}]);
                }
                cell
            })
            .collect();
        serde_json::to_vec(&serde_json::json!({"cells": list, "nbformat": 4, "nbformat_minor": 5})).unwrap()
    }

