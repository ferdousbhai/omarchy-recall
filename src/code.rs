/// "Swift", "Python", "Markdown": what a file's extension says it's written in.
pub fn language(path: &str) -> String {
    let path = Path::new(path);
    let ext = rules::extension(path);
    if let Some(language) = LANGUAGES.get(ext.as_str()) {
        return language.to_string();
    }
    let name = rules::name(path);
    if rules::is_code_file_name(name) || name.starts_with("Dockerfile") {
        return name.to_string();
    }
    if ext.is_empty() {
        "Text".into()
    } else {
        ext.to_uppercase()
    }
}

// MARK: Names in code

static IDENTIFIER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$").unwrap()
});

/// The words keyword search keeps a name from code as ("quantize_row_q8_0_ref" → quantize row q8 0 ref, as one
/// phrase), when the query is one: snake_case, camelCase, dotted, or with digits. None for words anyone would say
/// ("retry", "Renamer"), which are searched as words and by meaning.
pub fn identifier(query: &str) -> Option<Vec<String>> {
    let mut name = query.trim();
    if let Some(stripped) = name.strip_suffix("()") {
        name = stripped;
    }
    if !IDENTIFIER.is_match(name) {
        return None;
    }
    let camel = name.chars().skip(1).any(char::is_uppercase) && name.chars().any(char::is_lowercase);
    if !camel && !name.chars().any(|ch| "_.:#$".contains(ch) || ch.is_numeric()) {
        return None;
    }
    Some(
        name.to_lowercase()
            .split(|ch: char| !ch.is_alphanumeric())
            .filter(|word| !word.is_empty())
            .map(String::from)
            .collect(),
    )
}

/// The keyword search pattern for an identifier's words: one phrase, so they match only side by side, as written.
pub fn phrase(words: &[String]) -> String {
    format!("\"{}\"", words.join(" "))
}

static DEFINERS: LazyLock<HashSet<&str>> = LazyLock::new(|| {
    [
        "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
        "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
        "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*",
    ]
    .into_iter()
    .collect()
});
/// Words before a name that mean it's being used, not defined ("await name(…)", "return name(…)").
static USERS: LazyLock<HashSet<&str>> = LazyLock::new(|| {
    [
        "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
        "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
    ]
    .into_iter()
    .collect()
});

/// A word that starts a definition ("def", "func", "class", "@implementation"…).
pub fn defines_something(word: &str) -> bool {
    DEFINERS.contains(word) && !["let", "var", "const", "val"].contains(&word)
}

fn definition_strength(before: &str, after: &str, line: &str) -> u8 {
    let previous = before.split_whitespace().last().unwrap_or("");
    if DEFINERS.contains(previous) {
        return 2;
    }
    if before.starts_with("func (") && before.ends_with(')') {
        return 2; // a Go method
    }
    if before.starts_with("- (") || before.starts_with("+ (") {
        // an Objective-C method
        return if after.starts_with(':') || after.is_empty() || after.starts_with('{') || after.starts_with(';') { 2 } else { 0 };
    }
    // C-style: "static void name(…) {", "struct gguf_context * name(…)", not a call or an assignment.
    let Some(last) = before.chars().last() else { return 0 };
    if !after.starts_with('(')
        || USERS.contains(previous)
        || before.chars().any(|ch| "=(,.!?".contains(ch))
        || before.contains("->")
        || !(last.is_alphanumeric() || "*&>_]".contains(last))
    {
        return 0;
    }
    if line.trim_matches([' ', '\t']).ends_with(';') {
        1
    } else {
        2
    }
}

fn is_name_char(ch: char) -> bool {
    ch.is_alphanumeric() || ch == '_' || ch == '$'
}

/// Where `name` is in `line` as a whole name (not a part of a longer one), whatever its case: byte ranges.
fn occurrences(name: &str, line: &str) -> Vec<(usize, usize)> {
    let lower_line = line.to_lowercase();
    let lower_name = name.to_lowercase();
    if lower_line.len() != line.len() || lower_name.is_empty() {
        // Lowercasing changed lengths (rare scripts): compare as written.
        return line
            .match_indices(name)
            .map(|(at, found)| (at, at + found.len()))
            .filter(|(start, end)| {
                !line[..*start].chars().next_back().is_some_and(is_name_char)
                    && !line[*end..].chars().next().is_some_and(is_name_char)
            })
            .collect();
    }
    lower_line
        .match_indices(&lower_name)
        .map(|(at, found)| (at, at + found.len()))
        .filter(|(start, end)| {
            !line[..*start].chars().next_back().is_some_and(is_name_char)
                && !line[*end..].chars().next().is_some_and(is_name_char)
        })
        .collect()
}

/// Where `name` is defined in `text` (a stretch whose first line is `first`): the line, and how surely. 2 after a word
/// that defines something or as a C-style definition (a type before it, its parameters after it, no "=" or call around
/// it); 1 for a declaration (the same, ending in ";"). None when the stretch only uses it.
pub fn definition(name: &str, text: &str, first: usize) -> Option<(usize, u8)> {
    let mut best: Option<(usize, u8)> = None;
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        for (start, end) in occurrences(name, line) {
            let before = line[..start].trim_matches([' ', '\t']);
            let after = line[end..].trim_matches([' ', '\t']);
            let strength = definition_strength(before, after, line);
            if strength > best.map(|b| b.1).unwrap_or(0) {
                best = Some((first + offset, strength));
            }
            if strength == 2 {
                return best;
            }
        }
    }
    best
}

/// How comments and docstrings start.
const COMMENT_STARTS: [&str; 9] = ["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"];

/// Whether `line` has `word` (lowercased) as a word or as the start of a name's part (the "retry" of retryWithBackoff
/// and retry_with_backoff).
fn has(word: &str, line: &str) -> bool {
    let lower = line.to_lowercase();
    let same_length = lower.len() == line.len();
    for (at, _) in lower.match_indices(word) {
        let before = lower[..at].chars().next_back();
        let clear = before.map_or(true, |ch| !ch.is_alphanumeric());
        let capital = same_length && line[at..].chars().next().is_some_and(char::is_uppercase);
        if clear || capital {
            return true;
        }
    }
    false
}

/// The line (from `first`) to open at for `words`: the first line with one of them that defines something, else the
/// first such line of code (not a comment), else the first such line. None when none is there.
pub fn first_line(words: &[String], text: &str, first: usize) -> Option<usize> {
    let words: Vec<String> = words.iter().filter(|w| w.chars().count() >= 2).map(|w| w.to_lowercase()).collect();
    if words.is_empty() {
        return None;
    }
    let (mut first_code, mut first_any) = (None, None);
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        if !words.iter().any(|word| has(word, line)) {
            continue;
        }
        let trimmed = line.trim_matches([' ', '\t']);
        if trimmed.split_whitespace().take(4).any(defines_something) {
            return Some(first + offset);
        }
        if first_code.is_none() && !COMMENT_STARTS.iter().any(|start| trimmed.starts_with(start)) {
            first_code = Some(offset);
        }
        if first_any.is_none() {
            first_any = Some(offset);
        }
    }
    first_code.or(first_any).map(|offset| first + offset)
}

